const LocaleContext = createContext<{
  locale: Locale;
  t: Copy;
  setLocale: (locale: Locale) => void;
  compact: boolean;
  setCompact: (value: boolean) => void;
  demoMode: boolean;
  setDemoMode: (value: boolean) => void;
}>({
  locale: "en",
  t: copy.en,
  setLocale: () => undefined,
  compact: false,
  setCompact: () => undefined,
  demoMode: true,
  setDemoMode: () => undefined,
});

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("en");
  const [compact, setCompact] = useState(false);
  const [demoMode, setDemoMode] = useState(true);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  return (
    <LocaleContext.Provider
      value={{ locale, t: copy[locale], setLocale, compact, setCompact, demoMode, setDemoMode }}
    >
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  return useContext(LocaleContext);
}

export function reviewStatusName(t: Copy, status: string): string {
  if (status === "pending") return t.statusPending;
  if (status === "confirmed") return t.statusConfirmed;
  if (status === "overridden") return t.statusOverridden;
  if (status === "escalated") return t.statusEscalated;
  return status;
}

export function reviewActionName(t: Copy, action: string): string {
  if (action === "confirm") return t.actionConfirm;
  if (action === "override") return t.actionOverride;
  if (action === "escalate") return t.actionEscalate;
  if (action === "reassess") return t.actionReassess;
  return action;
}

export function fieldStatusName(t: Copy, status: string): string {
  if (status === "ok") return t.fieldValid;
  if (status === "missing") return t.fieldMissing;
  if (status === "implausible") return t.fieldImplausible;
  if (status === "conflicting") return t.fieldConflicting;
  return status;
}

export function duration(t: Copy, seconds: number, withSeconds = false): string {
  const total = Math.max(0, Math.round(seconds));
  const hours = Math.floor(total / 3600);
  const minutes = Math.floor((total % 3600) / 60);
  if (hours > 0) return t.durationHourMin(hours, minutes);
  return withSeconds ? t.durationMinSec(minutes, total % 60) : t.durationMin(minutes);
}

